static void selfCheck() {
  for (int r = 0; r < crippen::N_ROWS; ++r) {
    if (std::strcmp(IMPL[r].smarts, crippen::ROWS[r].smarts) != 0) {
      std::fprintf(stderr,
        "FATAL: row %d drifted. crippen_tables.h says\n  %s\nbut crippen.cpp implements\n  %s\n"
        "Regenerate the table and re-derive the predicate; do NOT paper over this.\n",
        r, crippen::ROWS[r].smarts, IMPL[r].smarts);
      std::exit(2);
    }
  }
}

static std::vector<Mol> load(const char* path) {
  FILE* f = std::fopen(path, "r");
  if (!f) { std::fprintf(stderr, "cannot open %s (run export_crippen.py mols)\n", path); std::exit(1); }
  int nm = 0;
  if (std::fscanf(f, "%d", &nm) != 1) std::exit(1);
  std::vector<Mol> out(nm);
  for (int k = 0; k < nm; ++k) {
    Mol& m = out[k];
    int nb = 0;
    if (std::fscanf(f, "%d %d", &m.n, &nb) != 2) std::exit(1);
    m.z.resize(m.n); m.arom.resize(m.n); m.sh.resize(m.n); m.tx.resize(m.n);
    m.deg.resize(m.n); m.chg.resize(m.n);
    std::vector<int> nHp(m.n), deg(m.n);
    for (int i = 0; i < m.n; ++i) {
      int z, d, nh, c, ar;
      if (std::fscanf(f, "%d %d %d %d %d", &z, &d, &nh, &c, &ar) != 5) std::exit(1);
      m.z[i] = (uint8_t)(z > 255 ? 255 : z); m.deg[i] = (uint8_t)d; nHp[i] = nh;
      m.chg[i] = (int8_t)c; m.arom[i] = (uint8_t)ar; deg[i] = d;
      m.tx[i] = (uint8_t)(d + nh);                       // SMARTS X == getTotalDegree()
      m.sh[i] = (uint8_t)nh;                             // + explicit H neighbours, added below
    }
    std::vector<int> eu(nb), ev(nb), ec(nb);
    std::vector<int> cnt(m.n + 1, 0);
    for (int e = 0; e < nb; ++e) {
      if (std::fscanf(f, "%d %d %d", &eu[e], &ev[e], &ec[e]) != 3) std::exit(1);
      cnt[eu[e]]++; cnt[ev[e]]++;
    }
    m.start.assign(m.n + 1, 0);
    for (int i = 0; i < m.n; ++i) m.start[i + 1] = m.start[i] + cnt[i];
    m.nbr.resize(2 * nb); m.bcode.resize(2 * nb);
    std::vector<int> cur(m.start.begin(), m.start.end() - 1);
    for (int e = 0; e < nb; ++e) {
      m.nbr[cur[eu[e]]] = ev[e]; m.bcode[cur[eu[e]]++] = (uint8_t)ec[e];
      m.nbr[cur[ev[e]]] = eu[e]; m.bcode[cur[ev[e]]++] = (uint8_t)ec[e];
    }
    // SMARTS `H` counts neighbouring explicit H ATOMS as well as the implicit count.
    for (int i = 0; i < m.n; ++i) {
      int extra = 0;
      for (int e = m.start[i]; e < m.start[i + 1]; ++e) if (m.z[m.nbr[e]] == 1) ++extra;
      m.sh[i] = (uint8_t)(nHp[i] + extra);
    }
    m.ref_logp.resize(m.n); m.ref_mr.resize(m.n); m.ref_row.resize(m.n);
    for (int i = 0; i < m.n; ++i) {
      int rr;
      if (std::fscanf(f, "%d %lf %lf", &rr, &m.ref_logp[i], &m.ref_mr[i]) != 3) std::exit(1);
      m.ref_row[i] = (uint8_t)rr;
    }
  }
  std::fclose(f);
  return out;
}

static int verify(const char* path, bool paranoid) {
  std::vector<Mol> mols = load(path);
  long long nat = 0, nbad = 0, nvalbad = 0, nmolbad = 0;
  std::vector<long long> okc(crippen::N_CLASSES + 1, 0), badc(crippen::N_CLASSES + 1, 0);
  std::vector<long long> rowhit(crippen::N_ROWS, 0);
  int shown = 0;
  for (size_t k = 0; k < mols.size(); ++k) {
    const Mol& m = mols[k];
    bool molbad = false;
    for (int i = 0; i < m.n; ++i) {
      int r = typeAtom(m, i);
      if (paranoid && typeAtomSlow(m, i) != r) {
        std::fprintf(stderr, "PARANOID: dispatch disagrees at mol %zu atom %d\n", k, i);
        return 3;
      }
      double lp = r < 0 ? crippen::UNMATCHED_LOGP : crippen::ROWS[r].logp;
      double mr = r < 0 ? crippen::UNMATCHED_MR   : crippen::ROWS[r].mr;
      int rr  = m.ref_row[i] == 255 ? -1 : (int)m.ref_row[i];
      int cls = rr < 0 ? crippen::N_CLASSES : crippen::ROW_CLASS[rr];
      ++nat;
      if (rr >= 0) ++rowhit[rr];
      // Compare the ROW RDKit picked, not just the numbers it produced. Two compensating
      // per-atom errors cancel in a molecule total; two classes with equal (logP, MR) would
      // cancel even per atom. The row index admits neither. The value check below is then a
      // second, independent assertion that the generated table itself is right.
      if (rr != r) {
        ++badc[cls]; ++nbad; molbad = true;
        if (shown < 25) {
          ++shown;
          std::fprintf(stderr,
            "  mol %zu atom %d Z=%d arom=%d chg=%d H=%d X=%d deg=%d : "
            "got row %d %s (%.6g,%.6g) want row %d %s (%.6g,%.6g)\n",
            k, i, (int)m.z[i], (int)m.arom[i], (int)m.chg[i], (int)m.sh[i], (int)m.tx[i],
            (int)m.deg[i], r, r < 0 ? "-" : crippen::ROWS[r].cls, lp, mr,
            rr, rr < 0 ? "-" : crippen::ROWS[rr].cls, m.ref_logp[i], m.ref_mr[i]);
        }
      } else {
        ++okc[cls];
        // EXACT. These are table lookups from the same source RDKit uses; widening this to a
        // tolerance could only ever hide a wrong number.
        if (lp != m.ref_logp[i] || mr != m.ref_mr[i]) { ++nvalbad; molbad = true; }
      }
    }
    if (molbad) ++nmolbad;
  }
  std::printf("\nper-atom exactness vs RDKit _CalcCrippenContribs\n");
  std::printf("  %zu molecules, %lld atoms\n", mols.size(), nat);
  std::printf("  same row picked : %lld / %lld  (%.6f%%)\n", nat - nbad, nat,
              100.0 * (double)(nat - nbad) / (double)nat);
  std::printf("  (logP, MR) exact: %lld / %lld  (%.6f%%)\n", nat - nbad - nvalbad, nat,
              100.0 * (double)(nat - nbad - nvalbad) / (double)nat);
  std::printf("  molecules exact : %lld / %lld\n", (long long)(mols.size() - nmolbad),
              (long long)mols.size());
  std::printf("\n  %-8s %12s %10s %9s\n", "class", "atoms", "exact", "pct");
  for (int c = 0; c <= crippen::N_CLASSES; ++c) {
    long long t = okc[c] + badc[c];
    const char* nm = c == crippen::N_CLASSES ? "(none)" : crippen::CLASS_NAMES[c];
    if (t == 0) { std::printf("  %-8s %12s %10s %9s   NEVER FIRES - UNTESTED\n", nm, "0", "-", "-"); continue; }
    std::printf("  %-8s %12lld %10lld %8.4f%%%s\n", nm, t, okc[c], 100.0 * (double)okc[c] / (double)t,
                badc[c] ? "   <-- MISMATCH" : "");
  }
  // Per-CLASS is what the report asks for, but a class can look green while one of its rows has
  // never been exercised (C1 has three rows, C26 four, O9 five). List those explicitly.
  int nz = 0;
  for (int r = 0; r < crippen::N_ROWS; ++r) if (!rowhit[r]) ++nz;
  std::printf("\n  rows never exercised by this corpus: %d / %d\n", nz, crippen::N_ROWS);
  for (int r = 0; r < crippen::N_ROWS; ++r)
    if (!rowhit[r]) std::printf("    row %-3d %-4s %s\n", r, crippen::ROWS[r].cls,
                                crippen::ROWS[r].smarts);
  if (paranoid) std::printf("\n  paranoid: dispatched and undispatched paths agree on every atom\n");
  return (nbad || nvalbad) ? 1 : 0;
}

static void bench(const char* path) {
  std::vector<Mol> mols = load(path);
  long long nat = 0;
  for (const Mol& m : mols) nat += m.n;
  size_t maxn = 0;
  for (const Mol& m : mols) maxn = std::max(maxn, (size_t)m.n);
  std::vector<double> lp(maxn + 1), mr(maxn + 1);

  std::vector<double> reps;
  double sink = 0;
  for (int rep = 0; rep < 11; ++rep) {
    auto t0 = std::chrono::steady_clock::now();
    for (const Mol& m : mols) {
      contribs(m, lp.data(), mr.data());
      // consume EVERY atom, not just atom 0: -O3 can inline contribs() and dead-code the atoms
      // whose results are never read, which would time a fraction of the molecule.
      for (int i = 0; i < m.n; ++i) sink += lp[i] + mr[i];
    }
    auto t1 = std::chrono::steady_clock::now();
    reps.push_back(std::chrono::duration<double, std::micro>(t1 - t0).count() / (double)mols.size());
  }
  std::sort(reps.begin(), reps.end());
  double med = reps[reps.size() / 2];
  std::printf("\ncrippen.cpp typer, %zu molecules, mean %.1f heavy atoms, 11 reps\n",
              mols.size(), (double)nat / (double)mols.size());
  std::printf("  median %.3f us/mol   min %.3f   max %.3f   (spread %+.1f%% / %+.1f%%)\n",
              med, reps.front(), reps.back(),
              100.0 * (reps.front() - med) / med, 100.0 * (reps.back() - med) / med);
  std::printf("  %.4f us per atom\n", med / ((double)nat / (double)mols.size()));
  if (sink == 12345.6789) std::printf("");   // keep the loop alive
}

int main(int argc, char** argv) {
  selfCheck();
  buildDispatch();
  const char* cmd = argc > 1 ? argv[1] : "verify";
  const char* path = argc > 2 ? argv[2] : "cpp/crip_mols.txt";
  if (!std::strcmp(cmd, "verify"))   return verify(path, false);
  if (!std::strcmp(cmd, "paranoid")) return verify(path, true);
  if (!std::strcmp(cmd, "bench"))    { bench(path); return 0; }
  std::fprintf(stderr, "usage: crippen [verify|paranoid|bench] [crip_mols.txt]\n");
  return 1;
}
