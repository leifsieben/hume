// [N,O,P,S,F,Cl,Br,I] as used by C3/C4 -- every member is an ALIPHATIC element symbol.
A_(q_C3het) {
  if (m.arom[i]) return false;
  switch (m.z[i]) { case 7: case 8: case 15: case 16: case 9: case 17: case 35: case 53:
                    return true; default: return false; }
}
// [!C;A;!#1] in C5 -- aliphatic, not hydrogen, and not aliphatic carbon (so simply not carbon,
// given the aliphatic constraint).
A_(q_aliHeavyNotC) { return !m.arom[i] && m.z[i] != 1 && m.z[i] != 6; }
// [A;!C;!N;!O;!S;!F;!Cl;!Br;!I;!#1] in C13. Note P is NOT excluded here -- an aromatic carbon
// bonded to phosphorus IS a C13. C27's exclusion list, one row later, DOES contain P.
A_(q_C13nbr) {
  if (m.arom[i]) return false;
  switch (m.z[i]) { case 1: case 6: case 7: case 8: case 16: case 9: case 17: case 35: case 53:
                    return false; default: return true; }
}
// [A;!C;!N;!O;!P;!S;!F;!Cl;!Br;!I;!#1] in C27.
A_(q_C27nbr) {
  if (m.arom[i]) return false;
  switch (m.z[i]) { case 1: case 6: case 7: case 8: case 15: case 16: case 9: case 17: case 35:
                    case 53: return false; default: return true; }
}
A_(q_z7or8)  { return m.z[i] == 7 || m.z[i] == 8; }                                // [#7,#8]
A_(q_C25nbr) { return !m.arom[i] && (m.z[i] == 6 || m.z[i] == 7 || m.z[i] == 8); }  // [C,N,O]
A_(q_aliNorO){ return !m.arom[i] && (m.z[i] == 7 || m.z[i] == 8); }                 // [N,O]
A_(q_aliOorS){ return !m.arom[i] && (m.z[i] == 8 || m.z[i] == 16); }                // [O,S]
A_(q_S2nbr)  { return !m.arom[i] && (m.z[i]==7 || m.z[i]==8 || m.z[i]==15 || m.z[i]==16); }
A_(q_H1nbr)  { return m.z[i] == 6 || m.z[i] == 1; }                                 // [#6,#1]
A_(q_notHC)  { return m.z[i] != 1 && m.z[i] != 6; }                                 // [!#1;!#6]
A_(q_H4dbl)  { // [#6,#7,O,S] -- the first two are element-only, the last two aliphatic
  if (m.z[i] == 6 || m.z[i] == 7) return true;
  return !m.arom[i] && (m.z[i] == 8 || m.z[i] == 16);
}
// [!#6;!#7;!#8;!#16] and [!#6;!#7;!#8] -- ELEMENT negation, so an aromatic n/o/s is excluded too.
// Data/Crippen.txt still shows the aliphatic-symbol forms [!C;!N;!O;!S] / [!C;!N;!O] here, which
// WOULD admit aromatic n. The compiled C++ table does not, and the compiled table is what
// _CalcCrippenContribs runs. See CPP_OVERRIDES in export_crippen.py.
A_(q_notCNOS){ switch (m.z[i]) { case 6: case 7: case 8: case 16: return false;
                                 default: return true; } }
A_(q_notCNO) { switch (m.z[i]) { case 6: case 7: case 8: return false;
                                 default: return true; } }
A_(q_O7nbr)  { // [!#1;!N;!S]
  if (m.z[i] == 1) return false;
  if (m.arom[i]) return true;
  return m.z[i] != 7 && m.z[i] != 16;
}
A_(q_CX4orAroC) { return m.z[i] == 6 && (m.arom[i] ? true : m.tx[i] == 4); }        // [CX4,c]
A_(q_z16chg0)   { return m.z[i] == 16 && m.chg[i] == 0; }                          // [#16;-0]
A_(q_aliNneg)   { return !m.arom[i] && m.z[i] == 7 && m.chg[i] <= -1 && m.chg[i] >= -3; }

#undef A_

typedef bool (*AtomQ)(const Mol&, int);

// ---------------------------------------------------------------------------------------------
// branch assignment
//
// SMARTS maps distinct query atoms to DISTINCT molecule atoms, so a pattern like
// [CH1X4]([N,O,P,S,F,Cl,Br,I])([A;!#1])[A;!#1] is an injective assignment problem, not three
// independent existence tests. With at most four branches and a handful of neighbours the honest
// backtracking search is both correct and faster than anything cleverer.
// ---------------------------------------------------------------------------------------------

struct Br { uint8_t bm; AtomQ q; };

static bool assignRec(const Mol& m, int b0, int nb, const Br* br, int k, int slot, uint32_t used) {
  if (slot == k) return true;
  for (int j = 0; j < nb; ++j) {
    if ((used >> j) & 1u) continue;
    if (!(m.bcode[b0 + j] & br[slot].bm)) continue;
    if (!br[slot].q(m, m.nbr[b0 + j])) continue;
    if (assignRec(m, b0, nb, br, k, slot + 1, used | (1u << j))) return true;
  }
  return false;
}

// Branches of `c`, with `ex` (the atom we arrived from) already consumed. ex < 0 means "root".
static inline bool branches(const Mol& m, int c, int ex, const Br* br, int k) {
  int b0 = m.start[c], nb = m.start[c + 1] - b0;
  if (nb > 32) nb = 32;                 // no real molecule reaches this; the mask is 32 bits
  uint32_t used = 0;
  if (ex >= 0) {
    for (int j = 0; j < nb; ++j) if (m.nbr[b0 + j] == ex) { used = 1u << j; break; }
  }
  return assignRec(m, b0, nb, br, k, 0, used);
}

// "does root have a neighbour reached by a bond in `bm` satisfying `q`" -- the k==1 fast path.
static inline int findNbr(const Mol& m, int root, uint8_t bm, AtomQ q, int from = 0) {
  for (int e = m.start[root] + from; e < m.start[root + 1]; ++e)
    if ((m.bcode[e] & bm) && q(m, m.nbr[e])) return e;
  return -1;
}
static inline bool hasNbr(const Mol& m, int root, uint8_t bm, AtomQ q) {
  return findNbr(m, root, bm, q) >= 0;
}

