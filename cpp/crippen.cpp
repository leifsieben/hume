#define THRU_O(inner_bm, inner_q)                                                        \
  for (int e = m.start[i]; e < m.start[i + 1]; ++e) {                                    \
    if (!(m.bcode[e] & BM_ANY)) continue;                                                \
    int o = m.nbr[e];                                                                    \
    if (!q_aliO(m, o)) continue;                                                         \
    B1(inner_bm, inner_q);                                                               \
    if (branches(m, o, i, _b, 1)) return true;                                           \
  }                                                                                      \
  return false

