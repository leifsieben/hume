// Wildman-Crippen atom typing, compiled.
//
// RDKit computes the per-atom (logP, MR) contribution pair by running 110 SMARTS patterns over
// the whole molecule in priority order and giving each atom the FIRST pattern it matches. That
// costs 79.3 us/mol COLD -- the second largest item in the HUME pipeline. It is a generic
// subgraph search being used to answer a question that, for 97 of the 110 rows, is a property of
// an atom and its immediate neighbours.
//
// This file replaces the search with straight-line code. The shape follows the measurement in
// cpp/spec_crippen.py rather than the other way round:
//
//   * 96 rows never look past the first shell. Each becomes a predicate over (element,
//     aromaticity, charge, H count, total degree) plus an injective assignment of at most four
//     branch atoms to neighbours.
//   * 14 rows reach two or three bonds, and every one of them is "one hop to a hinge atom, then
//     look at THAT atom's other substituents": the hydroxyl/enol hydrogens (H2/H3/H4) hinge on an
//     aliphatic O, and the carbonyl/carboxylate oxygens (O9/O10/O11/O12) hinge on an aliphatic C.
//     Both hinges are a one-line trigger. They are hand-written, with the grandparent explicitly
//     excluded so the query atoms stay distinct the way SMARTS requires.
//   * Dispatch is on (element, aromatic) first, because every row's first atom constrains the
//     element. An atom only ever walks the rows that could possibly claim it -- 26 for aliphatic
//     carbon, 14 for aromatic carbon, 1 for phosphorus, 0 for xenon.
//
// The numbers come from cpp/crippen_tables.h, generated by cpp/export_crippen.py from RDKit's own
// Data/Crippen.txt. Nothing here is hand-typed. Each predicate is stored NEXT TO the SMARTS string
// it implements and selfCheck() asserts at startup that the string still matches the generated
// table, so a future RDKit that reorders or edits a row fails loudly instead of drifting.
//
// SMARTS semantics this depends on, each verified against RDKit rather than assumed:
//   H  -> getTotalNumHs(true)   counts neighbouring explicit H ATOMS  (see `sh` below)
//   X  -> getTotalDegree()      == degree + getTotalNumHs(false)      (see `tx` below)
//   -  -> bond ORDER is single;  :  -> bond FLAG is aromatic;  default bond -> either
//   !C -> NOT aliphatic carbon; an aromatic c satisfies [!C]
//   +  -> charge exactly +1 (not "any positive"); -2 / -- -> exactly -2
//   an atom matching no row keeps (0.0, 0.0)
//
//   clang++ -O3 -std=c++17 -o cpp/crippen cpp/crippen.cpp
//   ./cpp/crippen verify        # per-atom vs RDKit, per-class breakdown
//   ./cpp/crippen paranoid      # dispatched path vs undispatched all-110-in-order path
//   ./cpp/crippen bench

