#define B3(a, b, c, d, e, f)       static const Br _b[] = {{a, b}, {c, d}, {e, f}};  (void)_b
#define B4(a,b,c,d,e,f,g,h)        static const Br _b[] = {{a,b},{c,d},{e,f},{g,h}}; (void)_b

