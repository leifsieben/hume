#!/usr/bin/env python
"""Verification harness for src/hume_core/counts_ext.h -- the 31 E_counts columns.

    .venv/bin/python verify_counts.py            dump the corpus, build, grade, bench
    .venv/bin/python verify_counts.py --n 2000   a subset, for a quick loop
    .venv/bin/python verify_counts.py --no-bench skip the timing pass

HOUSE RULE 1: NOT ONE DESCRIPTOR VALUE IS COMPUTED HERE. This file does exactly three things --
it serialises the boundary (the same fields src/hume/_extract.py serialises, from the same RDKit
calls), it shells out to a C++ driver built from counts_ext.h, and it compares that driver's
output with data/dedupe2/matrix.npz. Every number graded below was produced by C++.

WHY IT BUILDS ITS OWN DRIVER instead of importing `hume`. The contract forbids this agent from
touching src/hume_core/bindings.cpp, so counts_ext.h is not reachable from the extension yet.
The driver is written into build_counts/ (a build artefact directory, not repository source) and
compiled with the same `c++ -O3 -std=c++17` the other harnesses in cpp/ use, so the numbers are
produced by the same compiler and flags the shipped extension is built with.

WHAT IS GRADED. All 31 columns against mordred's values for all 20,000 corpus molecules, with
per-column exact / 1e-9 / 1e-6 / mismatch counts and NaN agreement, and every mismatch printed
with its SMILES. Two extra checks ride along:
  * counts_ext::driftGuard on every molecule -- ringPass over ringcount's own 49 specs must equal
    ringcount::compute cell for cell (see the note in counts_ext.h about the one duplicated pass).
  * the same driver run again over mordred's RAW ring set, so the ring divergence is a measured
    number and not a claim. --kekule adds the Kekule stability experiment of NOTES section 3.
"""
