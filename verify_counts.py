# ------------------------------------------------------------------------------------------------
# Boundary serialisation. Exactly the RDKit calls src/hume/_extract.py makes, and nothing else.
# ------------------------------------------------------------------------------------------------
def dump_mols(smis, strata, path: Path, nrot_ref, rings="repaired"):
    """`rings="repaired"` is the boundary's own `rings_for()` -- what HUME ships.
    `rings="raw"` is RDKit's `RingInfo().AtomRings()` verbatim, which is what mordred saw. The
    only difference between the two dumps is the ring CSR, so running the SAME driver over both
    isolates the ring set as the sole cause of any divergence -- and no descriptor value is ever
    computed on this side of the boundary."""
    from rdkit import Chem, RDLogger

    RDLogger.DisableLog("rdApp.*")
    from hume._rings import rings_for

    if rings not in ("repaired", "raw"):
        raise ValueError(rings)
    TYPE_BIT = {Chem.BondType.SINGLE: 1, Chem.BondType.DOUBLE: 2, Chem.BondType.TRIPLE: 4}
    CIP = "_CIPCode"
    strat_id = {s: i for i, s in enumerate(sorted(set(strata)))}
    out = [str(len(smis))]
    for idx, smi in enumerate(smis):
        m = Chem.MolFromSmiles(smi)
        if m is None:
            raise SystemExit(f"verify_counts: RDKit could not parse corpus molecule {idx}: {smi}")
        ats = list(m.GetAtoms())
        rs = rings_for(m) if rings == "repaired" else m.GetRingInfo().AtomRings()
        out.append(f"{len(ats)} {m.GetNumBonds()} {len(rs)} {int(nrot_ref[idx])} "
                   f"{strat_id[strata[idx]]}")
        ri = m.GetRingInfo()
        for a in ats:
            cip = 0
            if a.HasProp(CIP):
                cip = 1 if a.GetProp(CIP) == "R" else -1
            out.append(
                f"{a.GetAtomicNum()} {a.GetDegree()} {a.GetTotalNumHs()} {a.GetFormalCharge()} "
                f"{int(a.GetHybridization())} {int(a.GetIsAromatic())} {int(a.IsInRing())} {cip} "
                f"{ri.NumAtomRings(a.GetIdx())} {a.GetTotalValence()} {a.GetMass():.17g}")
        for b in m.GetBonds():
            bt = b.GetBondType()
            code = TYPE_BIT.get(bt, 0)
            if b.GetIsAromatic():
                code |= 8
            out.append(f"{b.GetBeginAtomIdx()} {b.GetEndAtomIdx()} {int(b.GetIsConjugated())} "
                       f"{int(b.IsInRing())} {code} {int(bt)} {b.GetBondTypeAsDouble():.17g}")
        for r in rs:
            out.append(str(len(r)) + " " + " ".join(str(i) for i in r))
    path.write_text("\n".join(out) + "\n")


# ------------------------------------------------------------------------------------------------
# THE KEKULE STABILITY EXPERIMENT that decided rule 4 for nBondsKS. Re-parses each aromatic
# molecule from many randomly re-ordered SMILES and asks whether RDKit's own kekulized SINGLE and
# DOUBLE counts move. This calls the REFERENCE (RDKit) for ground truth -- it does not implement
# a descriptor. --kekule to run it; it takes about a minute.
# ------------------------------------------------------------------------------------------------
def kekule_stability(smis, n_probe=650, n_try=40, seed=0):
    import random

    from rdkit import Chem, RDLogger

    RDLogger.DisableLog("rdApp.*")
    rng = random.Random(seed)

    def counts(m):
        mh = Chem.AddHs(m)
        Chem.Kekulize(mh)
        s = sum(1 for b in mh.GetBonds() if b.GetBondType() == Chem.BondType.SINGLE)
        d = sum(1 for b in mh.GetBonds() if b.GetBondType() == Chem.BondType.DOUBLE)
        return s, d

    cand = []
    for s in smis:
        m = Chem.MolFromSmiles(s)
        if m is not None and any(b.GetIsAromatic() for b in m.GetBonds()):
            cand.append(s)
    probe = rng.sample(cand, min(n_probe, len(cand)))
    moved_ks = moved_kd = reparses = 0
    examples = []
    for s in probe:
        m0 = Chem.MolFromSmiles(s)
        n = m0.GetNumAtoms()
        vks, vkd = set(), set()
        a, b = counts(m0)
        vks.add(a)
        vkd.add(b)
        for _ in range(n_try):
            perm = list(range(n))
            rng.shuffle(perm)
            m2 = Chem.MolFromSmiles(
                Chem.MolToSmiles(Chem.RenumberAtoms(m0, perm), canonical=False))
            if m2 is None:
                continue
            reparses += 1
            a, b = counts(m2)
            vks.add(a)
            vkd.add(b)
        if len(vks) > 1:
            moved_ks += 1
            if len(examples) < 5:
                examples.append((s, sorted(vks)))
        if len(vkd) > 1:
            moved_kd += 1
    return len(probe), len(cand), reparses, moved_ks, moved_kd, examples



def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=0, help="grade only the first N molecules")
    ap.add_argument("--no-bench", action="store_true")
    ap.add_argument("--no-rebuild", action="store_true")
    ap.add_argument("--kekule", action="store_true",
                    help="re-run the Kekule stability experiment behind NOTES_counts.md section 3")
    args = ap.parse_args()

    BUILD.mkdir(exist_ok=True)
    src = BUILD / "counts_driver.cpp"
    exe = BUILD / "counts_driver"
    src.write_text(DRIVER)
    if not args.no_rebuild or not exe.exists():
        cc = os.environ.get("CXX", "c++")
        cmd = [cc, "-O3", "-std=c++17", "-o", str(exe), str(src)]
        print("build:", " ".join(cmd))
        t0 = time.time()
        r = subprocess.run(cmd, cwd=ROOT)
        if r.returncode:
            raise SystemExit("verify_counts: the driver did not compile")
        print(f"  compiled in {time.time() - t0:.1f}s")

    names = subprocess.run([str(exe), "names"], cwd=ROOT, capture_output=True,
                           text=True, check=True).stdout.split()
    if names != COLS:
        raise SystemExit("verify_counts: counts_ext::col_name order does not match "
                         f"agent_groups.json E_counts\n  header: {names}\n  groups: {COLS}")
    print(f"columns: {len(names)} names, in agent_groups E_counts order  OK")

    d = np.load(ROOT / "data/dedupe2/matrix.npz", allow_pickle=True)
    md_names = list(d["md_names"])
    md_index = {n: i for i, n in enumerate(md_names)}
    MD = d["MD"]
    corpus = json.load(open(ROOT / "data/dedupe2/corpus.json"))
    smis, strata = corpus["smiles"], corpus["stratum"]
    N = args.n if args.n else len(smis)
    smis, strata = smis[:N], strata[:N]
    MD = MD[:N]
    print(f"corpus: {N:,} molecules, strata {sorted(set(strata))}")

    nrot_ref = MD[:, md_index["nRot"]]

    def run(rings, tag):
        """Serialise the boundary with `rings`, run the driver, return its (N, 31) values."""
        t0 = time.time()
        mols = BUILD / f"counts_mols_{tag}.txt"
        vals = BUILD / f"counts_values_{tag}.txt"
        dump_mols(smis, strata, mols, nrot_ref, rings=rings)
        print(f"boundary dumped ({rings} rings) in {time.time() - t0:.1f}s -> {mols}")
        if subprocess.run([str(exe), "dump", str(mols), str(vals)], cwd=ROOT).returncode:
            raise SystemExit("verify_counts: the driver failed (see message above)")
        A = np.loadtxt(vals, dtype=np.float64)
        if A.ndim == 1:
            A = A.reshape(1, -1)
        if A.shape != (N, len(COLS)):
            raise SystemExit(f"verify_counts: driver produced {A.shape}, "
                             f"expected {(N, len(COLS))}")
        return mols, A

    mols_txt, X = run("repaired", "repaired")

    # ---- grading -------------------------------------------------------------------------------
    print()
    print(f"{'column':13s} {'exact':>7s} {'1e-9':>6s} {'1e-6':>6s} {'MISMATCH':>9s} "
          f"{'nan-agree':>10s} {'nan-disagree':>13s}")
    total_bad = 0
    bad_detail = []
    for c, name in enumerate(COLS):
        ref = MD[:, md_index[name]].astype(np.float64)
        ours = X[:, c]
        rn, on = np.isnan(ref), np.isnan(ours)
        nan_agree = int((rn & on).sum())
        nan_dis = int((rn ^ on).sum())
        both = ~rn & ~on
        exact = int((ref[both] == ours[both]).sum())
        den = np.where(ref[both] != 0, np.abs(ref[both]), 1.0)
        rel = np.abs(ref[both] - ours[both]) / den
        w9 = int(((rel <= 1e-9) & (ref[both] != ours[both])).sum())
        w6 = int(((rel <= 1e-6) & (rel > 1e-9)).sum())
        bad = int(((rel > 1e-6)).sum()) + nan_dis
        total_bad += bad
        print(f"{name:13s} {exact:7d} {w9:6d} {w6:6d} {bad:9d} {nan_agree:10d} {nan_dis:13d}")
        if bad:
            idx = np.where(both)[0][rel > 1e-6]
            for i in list(idx) + list(np.where(rn ^ on)[0]):
                bad_detail.append((name, smis[i], float(ref[i]), float(ours[i])))

    print()
    if bad_detail:
        print(f"MISMATCHES ({len(bad_detail)}):")
        for name, smi, ref, ours in bad_detail[:200]:
            print(f"  {name:13s} ref={ref!r:>12} ours={ours!r:>12}  {smi}")
        if len(bad_detail) > 200:
            print(f"  ... and {len(bad_detail) - 200} more")
    print(f"TOTAL: {total_bad} mismatched cells out of {N * len(COLS):,} "
          f"({N:,} molecules x {len(COLS)} columns)")
    print("counts_ext::driftGuard passed on every molecule "
          f"({N * 49:,} ringPass-vs-ringcount::compute cells)")

    # ---- the ring divergence, measured by RUNNING THE SAME C++ TWICE ----------------------------
    # The only difference between the two dumps is the ring CSR -- repaired (`rings_for`, what
    # HUME ships) versus raw (`RingInfo().AtomRings()`, what mordred saw). So this isolates the
    # ring set as the sole cause of any divergence, without a line of descriptor logic in python.
    print()
    print("RING SET: mordred's raw Chem.GetSymmSSSR vs the boundary's repaired set")
    _, XR = run("raw", "raw")
    moved = set()
    for c, name in enumerate(COLS):
        ref = MD[:, md_index[name]].astype(np.float64)
        braw = int((XR[:, c] != ref).sum())
        brep = int((X[:, c] != ref).sum())
        if braw or brep:
            print(f"  {name:13s} raw-vs-mordred {braw:5d}   repaired-vs-mordred {brep:5d}")
        moved |= set(np.where(X[:, c] != XR[:, c])[0].tolist())
    print(f"  columns where the RAW ring set reproduces mordred exactly: "
          f"{sum(1 for c, n in enumerate(COLS) if (XR[:, c] == MD[:, md_index[n]]).all())}"
          f" of {len(COLS)}")
    print(f"  molecules where the two ring sets give different values: {len(moved)} of {N:,}")
    for i in sorted(moved)[:10]:
        d = [(n, float(XR[i, c]), float(X[i, c])) for c, n in enumerate(COLS)
             if XR[i, c] != X[i, c]]
        print(f"    {d}  {smis[i]}")

    # ---- the Kekule stability experiment behind NOTES_counts.md section 3 -----------------------
    if args.kekule:
        print()
        print("KEKULE STABILITY: is nBondsKS ill-posed? (contract rule 4)")
        npr, ncand, nrep, mks, mkd, ex = kekule_stability(smis)
        print(f"  {npr} aromatic molecules sampled from {ncand}, 40 random SMILES orderings each "
              f"({nrep} re-parses)")
        print(f"  RDKit's own kekulized SINGLE count moved on {mks} of {npr} molecules")
        print(f"  RDKit's own kekulized DOUBLE count moved on {mkd} of {npr} molecules")
        for e in ex:
            print(f"    {e}")
        print("  0 and 0 means the column is WELL-POSED and rule 4 says reproduce it.")

    # ---- timing --------------------------------------------------------------------------------
    if not args.no_bench:
        print()
        strat_names = sorted(set(strata))
        out = subprocess.run([str(exe), "bench", str(mols_txt)], cwd=ROOT,
                             capture_output=True, text=True, check=True).stdout
        MODE = {0: "counts_ext::compute alone -- THE MARGINAL COST in bindings.cpp",
                1: "+ constit::bondCount (if nBondsD/nBondsKD were recomputed, not wired)",
                2: "+ building constit::Mol and ringcount::Mol (standalone upper bound)"}
        print("TIMING (11 reps, file parse excluded; CONTENDED -- other agents build here too)")
        for mode in (0, 1, 2):
            print(f"  mode {mode}: {MODE[mode]}")
            tot_n, tot_us = 0, 0.0
            for line in out.strip().splitlines():
                f = line.split()
                if int(f[1]) != mode:
                    continue
                s, n, med, mean, sd = int(f[3]), int(f[4].split("=")[1]), float(f[6]), \
                    float(f[8]), float(f[10])
                print(f"    stratum {strat_names[s]:>10s}  n={n:5d}  median {med:7.3f} us/mol  "
                      f"mean {mean:7.3f}  sd {sd:6.3f}")
                tot_n += n
                tot_us += mean * n
            print(f"    ALL                    n={tot_n:5d}  mean   {tot_us / tot_n:7.3f} us/mol"
                  f"   ({100 * (tot_us / tot_n) / 830:.2f}% of HUME's ~830 us/mol budget)")

    return 1 if total_bad else 0


