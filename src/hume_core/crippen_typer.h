// The Wildman-Crippen atom typer, as a header the extension can call.
//
// WHAT THIS IS. cpp/crippen.cpp is a standalone program: 110 hand-derived predicates, a dispatch
// table, and a main() that reads cpp/crip_mols.txt and compares against RDKit. Its typer is
// verified BIT-IDENTICAL to rdMolDescriptors._CalcCrippenContribs on 2,869,048 atoms with all
// 110 rows exercised, and it costs 1.53 us/mol where RDKit's SMARTS pass costs ~78. That file
// keeps its verification harness and is NOT edited; this header is its computation half, lifted
// out of the I/O the same way hume_blocks.h was lifted out of cpp/hume.cpp's text loader.
//
// EVERYTHING BETWEEN THE `struct Mol` AND `contribs()` BELOW IS A VERBATIM COPY of lines 54-582
// of cpp/crippen.cpp. Two things were removed and nothing was added: the `ref_logp/ref_mr/
// ref_row` fields, which existed only to hold RDKit's answer for the comparison, and `deg`,
// which the text loader filled but no predicate reads. A copy is a drift risk, so it is guarded
// three ways rather than by good intentions:
//
//   1. Both files include the SAME generated cpp/crippen_tables.h, and both run the same
//      selfCheck(): every predicate stores the SMARTS string it implements next to itself and
//      the check asserts that it still equals the generated table's row. A predicate that
//      drifted from the table -- in either file -- fails loudly, here as an ImportError naming
//      both strings, because bindings.cpp calls check() from its module initialiser.
//   2. The dispatch lists are BUILT from the per-row {aro, zs} fields, not hand-listed, so they
//      cannot disagree with the predicates.
//   3. src/hume/_verify_crippen.py compares this header's output, through the extension, against
//      RDKit's own _CalcCrippenContribs atom by atom on the corpus.
//
// WHAT THE CALLER MUST SUPPLY, and what each field means in SMARTS terms -- these are the same
// five quantities cpp/export_crippen.py writes, derived from the arrays _extract.py already
// carries (see crippen_fill() in bindings.cpp):
//
//   z     atomic number                     tx  SMARTS X == degree + GetTotalNumHs(False)
//   arom  GetIsAromatic()                   sh  SMARTS H == GetTotalNumHs(False) + H neighbours
//   chg   formal charge
//   start/nbr/bcode   CSR adjacency; bcode is the 4-bit mask below, and the ORDER bit and the
//                     AROMATIC FLAG bit are independent -- `-` asks about the order, `:` about
//                     the flag, and the single bond joining biphenyl's two rings is the whole
//                     C20-vs-C19 distinction. It is passed in from Python rather than derived
//                     from the bond order, because a bond order of 1.0 does not imply SINGLE
//                     (dative bonds) and a TRIPLE bond can carry the aromatic flag; both occur
//                     in cpp/mols.smi.
