#define THRU_O(inner_bm, inner_q)                                                        \
  for (int e = m.start[i]; e < m.start[i + 1]; ++e) {                                    \
    if (!(m.bcode[e] & BM_ANY)) continue;                                                \
    int o = m.nbr[e];                                                                    \
