// ---------------------------------------------------------------------------------------------
// dispatch: which rows can an atom of this (element, aromaticity) possibly match, in row order
//
// Every row's first atom constrains the element, so this partition loses nothing. It is BUILT
// from the {aro, zs} fields above rather than hand-listed, so it cannot disagree with them; and
// `crippen paranoid` additionally re-runs the corpus through the undispatched all-110-rows-in-
// order path to prove the precomputed lists reproduce a plain linear scan atom for atom.
// ---------------------------------------------------------------------------------------------

static uint8_t DISP[119][2][crippen::N_ROWS];
static int     DISP_N[119][2];

static inline bool rowAdmits(int r, int z, int arom) {
  const Impl& im = IMPL[r];
  if (im.aro >= 0 && im.aro != arom) return false;
  for (int k = 0; k < 11 && im.zs[k]; ++k) if (im.zs[k] == z) return true;
  return false;
}

static void buildDispatch() {
  for (int z = 0; z < 119; ++z)
    for (int a = 0; a < 2; ++a) {
      int n = 0;
      for (int r = 0; r < crippen::N_ROWS; ++r) if (rowAdmits(r, z, a)) DISP[z][a][n++] = (uint8_t)r;
      DISP_N[z][a] = n;
    }
}

// -> row index, or -1 for "no pattern claims this atom" (contribution stays 0,0)
static inline int typeAtom(const Mol& m, int i) {
  int z = m.z[i], a = m.arom[i] ? 1 : 0;
  if (z > 118) return -1;
  const uint8_t* L = DISP[z][a];
  int n = DISP_N[z][a];
  for (int k = 0; k < n; ++k) if (IMPL[L[k]].fn(m, i)) return L[k];
  return -1;
}

// The undispatched reference path: every row, in file order, guard evaluated inline.
static int typeAtomSlow(const Mol& m, int i) {
  int z = m.z[i], a = m.arom[i] ? 1 : 0;
  if (z > 118) return -1;
  for (int r = 0; r < crippen::N_ROWS; ++r)
    if (rowAdmits(r, z, a) && IMPL[r].fn(m, i)) return r;
  return -1;
}

// ---------------------------------------------------------------------------------------------
// one-time setup, and the drift guard
//
// cpp/crippen.cpp runs selfCheck() and buildDispatch() out of main() and calls std::exit on
// drift. A header has no main(), so buildDispatch() runs from a static initialiser and the
// drift check RECORDS its verdict there rather than throwing: an exception escaping a static
// constructor is std::terminate, and a shared library that aborts the interpreter on load is a
// worse failure than one that explains itself. `check()` turns the verdict into an exception at
// a place that can carry it -- pybind11 makes it an ImportError -- and contribs() refuses to
// hand back numbers if anyone reaches it without having called check().
// ---------------------------------------------------------------------------------------------

static std::string DRIFT;

static void selfCheck() {
  for (int r = 0; r < crippen::N_ROWS; ++r) {
    if (std::strcmp(IMPL[r].smarts, crippen::ROWS[r].smarts) != 0) {
      DRIFT = std::string("hume: Crippen row ") + std::to_string(r) + " drifted. "
              "cpp/crippen_tables.h says '" + crippen::ROWS[r].smarts + "' but "
              "src/hume_core/crippen_typer.h implements '" + IMPL[r].smarts + "'. Regenerate "
              "the table and re-derive the predicate; do NOT paper over this.";
      return;
    }
  }
}

struct Init { Init() { selfCheck(); buildDispatch(); } };
static const Init INIT;

// Call once, somewhere that can report. Throws iff a predicate and the generated table disagree.
static void check() {
  if (!DRIFT.empty()) throw std::runtime_error(DRIFT);
}

static void contribs(const Mol& m, double* logp, double* mr) {
  if (!DRIFT.empty()) throw std::runtime_error(DRIFT);
  for (int i = 0; i < m.n; ++i) {
    int r = typeAtom(m, i);
    if (r < 0) { logp[i] = crippen::UNMATCHED_LOGP; mr[i] = crippen::UNMATCHED_MR; }
    else       { logp[i] = crippen::ROWS[r].logp;   mr[i] = crippen::ROWS[r].mr;   }
  }
}

