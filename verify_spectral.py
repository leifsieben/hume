# --------------------------------------------------------------------------- corpus -> blob


def serialise(smis, path, perm_seed=None):
    """Write the binary corpus blob the driver reads. RDKit only; no descriptor arithmetic.

    `perm_seed` RENUMBERS every molecule's atoms with a random permutation. All 65 columns are
    permutation invariants in exact arithmetic (every matrix here is permutation-SIMILAR under a
    renumbering, and VE1/VR1 are symmetric functions of the leading eigenvector), so the spread
    across seeds is a direct measurement of how much of each column is floating-point noise
    rather than molecule. See `--shuffle`.
    """
    from rdkit import Chem, RDLogger
    from rdkit.Chem import rdPartialCharges
    RDLogger.DisableLog("rdApp.*")

    rng = np.random.default_rng(perm_seed) if perm_seed is not None else None
    aoff, boff = [0], [0]
    az, afc, anh, ac, bu, bv, bo = [], [], [], [], [], [], []
    order_cache = {}
    for s in smis:
        m = Chem.MolFromSmiles(s)
        if m is None:
            raise ValueError(f"corpus SMILES did not parse: {s!r}")
        # mordred's Context hands explicit_hydrogens=False descriptors RemoveHs(mol, True).
        m = Chem.RemoveHs(m, updateExplicitCount=True)
        # mordred's AtomicProperty.calculate() runs this on its own molecule with RDKit's
        # default nIter; an exception there leaves the properties unset, which mordred turns
        # into an Error and the reference matrix into NaN. The sentinel reproduces that.
        ok = True
        try:
            rdPartialCharges.ComputeGasteigerCharges(m)
        except Exception:
            ok = False
        n = m.GetNumAtoms()
        new = rng.permutation(n) if rng is not None else np.arange(n)   # old index -> new index
        old = np.empty(n, int)
        old[new] = np.arange(n)                                         # new index -> old index
        atoms = [m.GetAtomWithIdx(int(i)) for i in old]
        for a in atoms:
            az.append(a.GetAtomicNum())
            afc.append(a.GetFormalCharge())
            anh.append(a.GetTotalNumHs())
            if not ok:
                ac.append(C_MISSING)
                continue
            # mordred's `c` getter, verbatim: the sum is INSIDE the conditional.
            try:
                q = (a.GetDoubleProp("_GasteigerCharge") + a.GetDoubleProp("_GasteigerHCharge")
                     if a.HasProp("_GasteigerHCharge") else 0.0)
            except Exception:
                q = C_MISSING
            ac.append(q)
        bonds = list(m.GetBonds())
        if rng is not None:
            bonds = [bonds[i] for i in rng.permutation(len(bonds))]
        for b in bonds:
            bu.append(int(new[b.GetBeginAtomIdx()]))
            bv.append(int(new[b.GetEndAtomIdx()]))
            bt = b.GetBondType()
            o = order_cache.get(bt)
            if o is None:
                o = order_cache[bt] = b.GetBondTypeAsDouble()
            bo.append(o)
        aoff.append(len(az))
        boff.append(len(bu))

    with open(path, "wb") as f:
        np.array([len(smis), len(az), len(bu)], np.int32).tofile(f)
        np.array(aoff, np.int32).tofile(f)
        np.array(boff, np.int32).tofile(f)
        np.array(az, np.int32).tofile(f)
        np.array(afc, np.int32).tofile(f)
        np.array(anh, np.int32).tofile(f)
        np.array(ac, np.float64).tofile(f)
        np.array(bu, np.int32).tofile(f)
        np.array(bv, np.int32).tofile(f)
        np.array(bo, np.float64).tofile(f)
    return path


