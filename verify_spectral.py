"""Verification harness for src/hume_core/spectral.h -- the 65 B_spectral columns.

    .venv/bin/python verify_spectral.py             # build, run, grade, time
    .venv/bin/python verify_spectral.py --ref       # build the float64 mordred reference only
    .venv/bin/python verify_spectral.py --no-ref    # skip it (float32 grade only, no mordred)
    .venv/bin/python verify_spectral.py --shuffle   # + the atom-renumbering stability probe
    .venv/bin/python verify_spectral.py --limit N   # first N corpus molecules only

NO DESCRIPTOR VALUE IS COMPUTED IN PYTHON HERE (contract rule 1). This file does three things:
it serialises the corpus into a binary blob, it shells out to a C++ driver that includes
spectral.h and nothing else of ours, and it compares the driver's doubles against reference
values that came out of mordred itself.

WHY THERE ARE TWO REFERENCES, and this is the first finding of the exercise.
`data/dedupe2/matrix.npz` stores `MD` as **float32**. A float32 cell carries ~7 significant
decimal digits, so "bit-identical" against it is a statement about the first 24 bits of a
double and the contract's 1e-9 tier cannot be evaluated at all. The npz is therefore used as
the FULL-CORPUS check (all 20,000 molecules, 65 columns, including every NaN), and a float64
reference is regenerated from mordred 1.2.0 for the same corpus and cached in the scratchpad;
that one carries the exactness grade. The two are cross-checked against each other so the
regeneration cannot silently be of a different quantity.

The driver is GENERATED into build_spectral/ rather than committed, because the contract
confines this agent to three files and a build directory. It is a build artefact: delete
build_spectral/ and this script reproduces it.
"""
