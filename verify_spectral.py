def build_reference(limit, allow_build=True):
    SCRATCH.mkdir(parents=True, exist_ok=True)
    out = SCRATCH / f"mordred_f64_{limit or 'all'}.npy"
    if out.exists():
        return out
    if not allow_build:
        return None
